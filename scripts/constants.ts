/**
 * Centralized Constants for fullstack-audit-skill
 * Single source of truth for versioning, engine metadata, and harness definitions.
 */

export const FULLSTACK_AUDIT_VERSION = "2.14.0";
export const FULLSTACK_AUDIT_ENGINE = "Living Fullstack Atlas & Minimalist Engine v2.14.0";
export const FULLSTACK_AUDIT_RELEASE_DATE = "2026-10-25";

export type AuditProfile = "triad" | "standalone" | "custom";

export interface ProfileOptions {
  profile: AuditProfile;
  ponytail: boolean;
  caveman: boolean;
  superpowers: boolean;
}

export interface VersionInfo {
  version: string;
  engine: string;
  releaseDate: string;
}

export function getVersionBanner(): string {
  return `fullstack-audit v${FULLSTACK_AUDIT_VERSION} (engine: ${FULLSTACK_AUDIT_ENGINE}, released: ${FULLSTACK_AUDIT_RELEASE_DATE})`;
}

export function getAtlasProvenanceHeader(title: string, subtitle: string): string {
  return `<!-- Generated by fullstack-audit v${FULLSTACK_AUDIT_VERSION} on ${FULLSTACK_AUDIT_RELEASE_DATE} -->
# ${title}

> ${subtitle}
> **Atlas Version**: \`v${FULLSTACK_AUDIT_VERSION}\` | **Engine**: \`${FULLSTACK_AUDIT_ENGINE}\` | **Status**: Verified Clean

`;
}

export interface AtlasIndexEntry {
  symbol: string;
  category: "route" | "component" | "overlay" | "icon" | "query" | "api" | "model" | "action" | "slice" | "label" | "test" | "symbol" | "live-dot" | "capsule-pill";
  file: string;
  line: number;
  meta?: string;
  atlasRef: string;
}

export interface CausalGraphNode {
  id: string;
  label?: string;
  type: string;
}

export interface CausalGraphLink {
  source: string;
  target: string;
  type: string;
}

export interface CausalGraph {
  nodes: CausalGraphNode[];
  links: CausalGraphLink[];
}

export interface AtlasIndex {
  version: string;
  engine: string;
  generatedAt: string;
  totalEntries: number;
  entries: AtlasIndexEntry[];
  causalGraph?: CausalGraph;
}
